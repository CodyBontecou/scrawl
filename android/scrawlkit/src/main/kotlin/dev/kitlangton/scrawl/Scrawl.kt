    /**
     * Touches go to the timeline while recording (moves at most 30 a second per finger). A touch that
     * began before the recording was started (the trigger's fingers) is ignored.
     */
    internal fun recordTouches(event: MotionEvent, window: View) {
        if (!isRecording && !isStarting) return
        // Coordinates are in the foreground activity's window (the movie's frame), as iOS's are in
        // its full-screen app window: a touch in a dialog lands where it is on that screen.
        val scene = focusedRoot() ?: window
        touchWindow = scene
        val density = scene.resources.displayMetrics.density.toDouble()
        val windowOrigin = IntArray(2).also { window.getLocationOnScreen(it) }
        val sceneOrigin = IntArray(2).also { scene.getLocationOnScreen(it) }
        val dx = (windowOrigin[0] - sceneOrigin[0]).toFloat()
        val dy = (windowOrigin[1] - sceneOrigin[1]).toFloat()
        val action = event.actionMasked
        fun one(index: Int, phase: String) {
            val pointer = event.getPointerId(index)
            val id = touchIDs[pointer] ?: if (phase == "down") nextTouchID++.also { touchIDs[pointer] = it } else return
            val point = Vec((event.getX(index) + dx) / density, (event.getY(index) + dy) / density)
            if (phase == "move") {
                // Only fingers that moved (UIKit sends touchesMoved for those alone).
                val last = lastPointer[pointer]
                if (last != null && last.first == event.getX(index) && last.second == event.getY(index)) return
            }
            lastPointer[pointer] = event.getX(index) to event.getY(index)
            if (phase == "move") {
                lastTouchMoveNs = System.nanoTime()
                draggingTouchIDs += id
            }
            if (phase == "down") {
                val label = HitLabels.label(window, event.getX(index), event.getY(index))
                if (label != null) touchLabels[id] = label else touchLabels.remove(id)
            }
            val label = touchLabels[id]
            val ended = phase == "up" || phase == "cancel"
            if (ended) {
                lastPointer.remove(pointer)
                touchIDs.remove(pointer)
                touchLabels.remove(id)
                draggingTouchIDs.remove(id)
            }
            val seconds = elapsedSeconds() ?: return
            trackHold(id, point, phase)
            if (phase == "move") {
                val last = lastTouchLog[id]
                if (last != null && seconds - last < 1.0 / 30) return
            }
            lastTouchLog[id] = seconds
            touchLog += JSONObject().apply {
                put("t", round(seconds))
                put("id", id)
                put("x", round(point.x))
                put("y", round(point.y))
                put("phase", phase)
                if (!label.isNullOrEmpty()) put("label", label)
            }
        }
        when (action) {
            MotionEvent.ACTION_DOWN, MotionEvent.ACTION_POINTER_DOWN -> one(event.actionIndex, "down")
            MotionEvent.ACTION_MOVE -> for (i in 0 until event.pointerCount) one(i, "move")
            MotionEvent.ACTION_UP, MotionEvent.ACTION_POINTER_UP -> one(event.actionIndex, "up")
            MotionEvent.ACTION_CANCEL -> for (i in 0 until event.pointerCount) one(i, "cancel")
        }
        // Every finger has lifted.
        if (action == MotionEvent.ACTION_UP || action == MotionEvent.ACTION_CANCEL) {
            touchIDs.clear(); touchLabels.clear(); holdStarts.clear(); draggingTouchIDs.clear(); lastPointer.clear()
        }
    }

    /** Each finger's last position in its window's px, so a move that didn't move it isn't logged. */
    private val lastPointer = HashMap<Int, Pair<Float, Float>>()

    /** A light tick when a finger has held still for a moment, so a deliberate "this one" press is felt. */
    private fun trackHold(id: Int, point: Vec, phase: String) {
        when (phase) {
            "down" -> {
                holdStarts[id] = point
                main.launch {
                    delay(420)
                    if (isRecording && holdStarts.remove(id) != null) haptics.rigid()
                }
            }
            "move" -> holdStarts[id]?.let { if (hypot(point.x - it.x, point.y - it.y) > 12) holdStarts.remove(id) }
            else -> holdStarts.remove(id)
        }
    }

    // Mac / agent delivery

    private suspend fun deliverToMacOrShare(finished: FinishedRecording) {
        val framed = withContext(Dispatchers.IO) {
            val movieData = runCatching { finished.recording.movie.readBytes() }.getOrDefault(ByteArray(0))
            val n = finished.timelineData.size
            byteArrayOf((n ushr 24).toByte(), (n ushr 16).toByte(), (n ushr 8).toByte(), n.toByte()) + finished.timelineData + movieData
        }
        // The address that answered when recording started goes alone, and gets longer to answer.
        val urls = reachableURL?.let { listOf(it) } ?: serverURLs
        val replyWait = if (reachableURL == null) 15 else 45
        val bearer = token?.trim()
        val deliveryMarker = deliveryMarker(finished.sentMarker)
        val winner = CompletableDeferred<IngestReply?>()
        val jobs = mutableListOf<Job>()
        val scope = CoroutineScope(Dispatchers.IO)
        // Counted before any task starts, so an early failure can't look like the last one.
        val posting = if (bearer.isNullOrEmpty()) emptyList() else urls
        var remaining = posting.size + 1
        fun done(reply: IngestReply?) {
            synchronized(winner) {
                remaining -= 1
                if (reply != null) winner.complete(reply) else if (remaining == 0) winner.complete(null)
            }
        }
        // 1. Direct HTTP POST to Scrawl on the Mac (LAN + Tailscale in parallel).
        for (base in posting) {
            jobs += scope.launch { done(postIngest(base, framed, bearer!!, replyWait)) }
        }
        // 2. USB fallback: Scrawl on the Mac pulls the files over adb, builds the bundle, and writes
        // `<stamp>.delivery` (its reply) and then `<stamp>.sent` back.
        jobs += scope.launch {
            var reply: IngestReply? = null
            for (i in 0 until 75) {
                delay(400)
                val text = runCatching { finished.sentMarker.readText().trim() }.getOrNull()
                if (!text.isNullOrEmpty()) {
                    reply = IngestReply.fromSentMarker(text, runCatching { deliveryMarker.readBytes() }.getOrNull())
                    break
                }
            }
            done(reply)
        }
        val reply = winner.await()
        jobs.forEach { it.cancel() }
        if (reply != null) {
            finished.readyMarker.delete(); finished.sentMarker.delete(); deliveryMarker.delete()
            presentSent(reply)
        } else {
            // Keep `.ready` so the Mac still picks it up the next time the phone is cabled.
            presentFailure(StripFailure.Unreachable, recording = finished.recording)
        }
    }

    private suspend fun deliverHosted(finished: FinishedRecording) {
        syncOutbox()
        val outbox = outbox
        val target = hostedURL
        if (outbox == null || target == null) {
            presentFailure(StripFailure.NotSaved, recording = finished.recording); return
        }
        val entry = try {
            withContext(Dispatchers.IO) {
                outbox.enqueue(finished.timelineData, finished.recording.movie, target, finished.recordedAt, if (pairingRevoked) Outbox.Failure.Unauthorized else null)
            }
        } catch (e: Exception) {
            Log.w(TAG, "Scrawl: could not save the recording for sending: ${e.message}")
            presentFailure(StripFailure.NotSaved, recording = finished.recording)
            return
        }
        // The outbox holds the only copy from here on.
        delete(finished)
        entry.failure?.let {
            presentFailure(StripFailure.of(it), entry = entry.id); return
        }
        // Unless a new recording took the strip over while this one was being written.
        if (uploadStatus == UploadStatus.Sending) {
            shownEntry = entry.id
            sendProgress = null
            isSendStalled = false
            delivery = DeliveryTracker(entry.id, pathSatisfied, System.currentTimeMillis())
        }
        outbox.kick(true)
        OutboxWorker.schedule(app, outbox)
        refreshDelivery()
    }

    /** "Sent to …", or the two-line "On your Mac", which stays up a little longer to be read. */
    private suspend fun presentSent(reply: IngestReply) {
        statusID += 1
        val id = statusID
        pendingSent = null
        uploadStatus = UploadStatus.Sent(reply)
        haptics.success()
        delay(if (reply.isDelivered) 2_200 else 3_500)
        if (statusID != id || uploadStatus !is UploadStatus.Sent) return
        uploadStatus = UploadStatus.Idle
        hideOverlayAfterExit()
    }

    /** Offline, or waiting to retry: calm, with a success haptic, then the strip leaves. */
    private fun presentQueued() {
        statusID += 1
        val id = statusID
        uploadStatus = UploadStatus.Queued
        haptics.success()
        main.launch {
            delay(3_500)
            if (statusID != id || uploadStatus != UploadStatus.Queued) return@launch
            shownEntry = null
            uploadStatus = UploadStatus.Idle
            hideOverlayAfterExit()
        }
    }

    /** The failed bubble, with Share (of a LAN [recording], or of an outbox [entry]). */
    private suspend fun presentFailure(failure: StripFailure, recording: Recording? = null, entry: String? = null) {
        statusID += 1
        val id = statusID
        deliveryFailure = failure
        failedRecording = recording
        failedEntry = entry
        showOverlay()
        uploadStatus = UploadStatus.Failed
        haptics.warning()
        delay(8_000)
        if (statusID != id || uploadStatus != UploadStatus.Failed) return
        uploadStatus = UploadStatus.Idle
        failedRecording = null
        failedEntry = null
        hideOverlayAfterExit()
    }

    /** The failed bubble's Share button. */
    internal fun shareFailedRecording() {
        val recording = failedRecording
        val entry = failedEntry
        if (recording == null && entry == null) return
        failedRecording = null
        failedEntry = null
        uploadStatus = UploadStatus.Idle
        main.launch { hideOverlayAfterExit() }
        if (!sharesWhenDone) return
        if (recording != null) {
            share(listOf(recording.movie, recording.timeline))
        } else if (entry != null) {
            val outbox = outbox ?: return
            main.launch {
                // The payload stays queued; Share gets temporary copies of its files.
                val folder = File(app.cacheDir, "ScrawlShare")
                val files = runCatching { withContext(Dispatchers.IO) { outbox.extract(entry, folder) } }.getOrNull() ?: return@launch
                share(listOf(files.first, files.second), cleanup = true)
            }
        }
    }

    /**
     * Checks each Scrawl address and remembers the first that answers. The HTTPS endpoint answering
     * 401/403 means the link was revoked: the strip says so and the recording is kept as failed.
     */
    private suspend fun findMac() {
        reachableURL = null
        val urls = serverURLs
        val bearer = token?.trim()?.takeIf { it.isNotEmpty() } ?: return
        val (reachable, revoked) = HealthProbe.probe(urls, bearer)
        reachableURL = reachable
        if (hostedURL == null) return
        if (reachable?.lowercase()?.startsWith("https") == true) {
            pairingRevoked = false
        } else if (revoked) {
            pairingRevoked = true
            if (isRecording || isStarting) showNotice(StripNotice.linkExpired, 5_000)
        }
    }

    private fun deliveryMarker(sentMarker: File) = File(sentMarker.parentFile, sentMarker.nameWithoutExtension + ".delivery")

    /** Uploads to a Mac, which answers within [replyWait] seconds (`X-Scrawl-Wait`). */
    private fun postIngest(base: String, payload: ByteArray, token: String, replyWait: Int): IngestReply? = runCatching {
        val c = URL("$base/ingest").openConnection() as HttpURLConnection
        try {
            c.requestMethod = "POST"
            c.doOutput = true
            c.connectTimeout = 10_000
            c.readTimeout = (replyWait + 15) * 1000
            c.setFixedLengthStreamingMode(payload.size)
            c.setRequestProperty("Content-Type", "application/octet-stream")
            c.setRequestProperty("Authorization", "Bearer $token")
            c.setRequestProperty("X-Scrawl-Wait", replyWait.toString())
            c.outputStream.use { it.write(payload) }
            val status = c.responseCode
            if (status !in 200..299) return@runCatching null
            IngestReply.fromBody(c.inputStream.use { it.readUpTo(64 * 1024) })
        } finally {
            c.disconnect()
        }
    }.getOrNull()

