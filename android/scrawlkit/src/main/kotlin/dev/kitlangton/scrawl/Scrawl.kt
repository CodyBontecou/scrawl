            if (isRecording || isStarting) {
                isRecording = false
                isStarting = false
                isDrawing = false
                startedAt = null
                pendingFinish = null
                recorder?.cancel()
                recorder = null
            }
            if (isDiscardPending) finalizeDiscard()
            hideOverlay()
        }
        notifyConfigurationChanged()
    }

