    // Freehand drawing on the overlay

    /** A finished stroke from the overlay: its smoothed samples go on the timeline. */
    internal fun recordStroke(samples: List<InkSample>): Int? {
        val startedAt = startedAt ?: return null
        val first = samples.firstOrNull() ?: return null
        val last = samples.last()
        val offset = recordingOffset(startedAt)
        val points = JSONArray(samples.map { JSONArray(listOf(round(it.point.x), round(it.point.y), round(max(it.time + offset, 0.0)))) })
        completedStrokes = completedStrokes + listOf(samples.map { it.point })
        strokeLog += JSONObject().apply {
            put("t0", round(max(first.time + offset, 0.0)))
            put("t1", round(max(last.time + offset, 0.0)))
            put("points", points)
        }
        return strokeLog.size - 1
    }

    /** The overlay started fading these strokes at [uptime]: `fadeAt` says when they left the screen. */
    internal fun recordFade(strokes: List<Int>, uptime: Double) {
        val startedAt = startedAt ?: return
        val t = round(max(uptime + recordingOffset(startedAt), 0.0))
        for (index in strokes) strokeLog.getOrNull(index)?.put("fadeAt", t)
    }

    /** Add to a touch time (seconds since boot, uptime clock) to get seconds into the recording. */
    private fun recordingOffset(startedAt: RecordingStart): Double =
        -(startedAt.monoNs / 1e9) + (System.nanoTime() / 1e9 - android.os.SystemClock.uptimeMillis() / 1000.0)

    private fun elapsedSeconds(): Double? = startedAt?.let { (System.nanoTime() - it.monoNs) / 1e9 }

