        }
    }

    private fun rebaseEarlyInput(shift: Double) {
        if (shift == 0.0) return
        markers = markers.map { round(max(0.0, it + shift)) }
        for (e in events) e.put("t", round(max(0.0, e.getDouble("t") + shift)))
        for (t in touchLog) t.put("t", round(max(0.0, t.getDouble("t") + shift)))
        for (s in strokeLog) {
            for (key in listOf("t0", "t1", "fadeAt")) if (s.has(key)) s.put(key, round(max(0.0, s.getDouble(key) + shift)))
            val points = s.getJSONArray("points")
            for (i in 0 until points.length()) {
                val p = points.getJSONArray(i)
                p.put(2, round(max(0.0, p.getDouble(2) + shift)))
            }
        }
    }

