    // Activities, windows, install

    private var foregroundActivityRef: java.lang.ref.WeakReference<Activity>? = null
    private val foregroundActivity: Activity? get() = foregroundActivityRef?.get()?.takeIf { !it.isFinishing }
    private var startedActivities = 0
    private var resumedActivities = 0
    private val routers = WeakHashMap<Window, TouchRouter>()
    private val layoutListeners = WeakHashMap<View, ViewTreeObserver.OnGlobalLayoutListener>()
    private var installed = true

    /** Whether links and touches are handled: installed with `isEnabled`. */
    internal val isEnabled: Boolean get() = installed

    internal fun windowsChanged() {
        if (!isConfigured) return
        main.launch {
            syncInstall()
            overlay?.raiseIfCovered()
        }
    }

    /**
     * Wraps every app window's callback while configured (and the host enabled); unwraps when not.
     * Unconfigured devices stay completely inert.
     */
    private fun syncInstall() {
        val active = installed && isConfigured
        val roots = Windows.roots()
        if (!active) {
            for ((window, router) in routers.entries.toList()) {
                if (window.callback === router) window.callback = router.original
            }
            routers.clear()
            for ((view, listener) in layoutListeners.entries.toList()) runCatching { view.viewTreeObserver.removeOnGlobalLayoutListener(listener) }
            layoutListeners.clear()
            return
        }
        for (root in roots) {
            val overlayRoot = overlay?.root
            if (root.view === overlayRoot) continue
            val window = Windows.windowOf(root.view) ?: continue
            wrap(window)
        }
        foregroundActivity?.window?.let { wrap(it) }
    }

    private fun wrap(window: Window) {
        if (routers.containsKey(window)) return
        val callback = window.callback ?: return
        // Already ours (another instance's router is wrapped like any other callback).
        if (callback is TouchRouter && callback.scrawl === this) return
        val router = TouchRouter(callback, window, this)
        window.callback = router
        routers[window] = router
        val decor = window.decorView
        val listener = ViewTreeObserver.OnGlobalLayoutListener { keyboard.update(foregroundActivity?.window?.decorView) }
        decor.viewTreeObserver.addOnGlobalLayoutListener(listener)
        decor.viewTreeObserver.addOnScrollChangedListener { lastScrollNs = System.nanoTime() }
        layoutListeners[decor] = listener
    }

    internal fun focusedRoot(): View? = foregroundActivity?.window?.decorView

    private val lifecycle = object : Application.ActivityLifecycleCallbacks {
        override fun onActivityCreated(activity: Activity, savedInstanceState: Bundle?) {
            Windows.track(activity)
            if (activity is ScrawlRequestActivity) return
            val extras = activity.intent?.extras
            if (LaunchOverrides.extras == null && extras != null && extras.keySet().any { it.startsWith("scrawl-") }) {
                LaunchOverrides.extras = extras
                applyConfig(resolvedConfig(app, ScrawlConfig.load(app)))
            }
            // Only a fresh launch carries a new link (a recreated activity keeps its old intent), and
            // only while ScrawlKit is enabled, as `.scrawl(isEnabled:)` gates `onOpenURL` on iOS.
            if (savedInstanceState == null && installed) handleIntent(activity.intent)
        }

        override fun onActivityStarted(activity: Activity) {
            startedActivities += 1
            // The app came to the foreground (iOS: willEnterForeground): retry what's waiting now.
            if (startedActivities == 1) {
                if (isConfigured) outbox?.kick(true)
                recorder?.appWillEnterForeground()
            }
        }

        override fun onActivityResumed(activity: Activity) {
            if (activity is ScrawlRequestActivity) return
            resumedActivities += 1
            foregroundActivityRef = java.lang.ref.WeakReference(activity)
            if (isConfigured) {
                syncInstall()
                // The overlay follows the foreground activity.
                overlay?.let { if (it.hostActivity !== activity) it.attach(activity) }
                keyboard.update(activity.window.decorView)
            }
            shareCleanup?.let { files -> files.forEach { it.delete() }; shareCleanup = null }
            showPendingSent()
        }

        override fun onActivityPaused(activity: Activity) {
            if (activity is ScrawlRequestActivity) return
            resumedActivities = max(0, resumedActivities - 1)
        }

        override fun onActivityStopped(activity: Activity) {
            startedActivities = max(0, startedActivities - 1)
            if (startedActivities == 0) {
                // The app left the foreground: the recorder stops and the recording is sent.
                recorder?.appDidEnterBackground()
            }
        }

        override fun onActivitySaveInstanceState(activity: Activity, outState: Bundle) = Unit
        override fun onActivityDestroyed(activity: Activity) {
            Windows.untrack(activity)
            // The overlay's window goes with its activity; it comes back over the next one resumed.
            overlay?.let { if (it.hostActivity === activity) it.detachWindow() }
        }
    }

    /** Tests construct a [Scrawl] directly: track activities without [install]. */
    internal fun attachForTesting(application: Application) {
        application.registerActivityLifecycleCallbacks(lifecycle)
        notifyConfigurationChanged() // as install() does: keyboard tracking, windows, outbox
    }

    internal fun detachForTesting(application: Application) {
        application.unregisterActivityLifecycleCallbacks(lifecycle)
        installed = false
        syncInstall()
        hideOverlay()
    }

    internal fun activityResumedForTesting(activity: Activity) {
        Windows.track(activity)
        startedActivities += 1
        lifecycle.onActivityResumed(activity)
    }

    private fun handleIntent(intent: Intent?) {
        val data = intent?.data?.toString() ?: return
        handleSetupURL(data)
    }

    /** Handles a setup or reset link; returns true when [url] was a valid Scrawl link. */
    fun handleSetupURL(url: String): Boolean {
        val action = ScrawlConfig.parseSetupURL(url) ?: return false
        val now = System.nanoTime()
        val duplicate = lastSetupURLHandled?.let { it.first == url && now - it.second < 250_000_000L } ?: false
        lastSetupURLHandled = url to now
        when (action) {
            is ScrawlConfig.SetupAction.Configure -> {
                ScrawlConfig.save(app, action.config)
                applyConfig(resolvedConfig(app, action.config) ?: action.config)
                if (!duplicate) haptics.success()
            }
            ScrawlConfig.SetupAction.Reset -> {
                ScrawlConfig.delete(app)
                applyConfig(resolvedConfig(app, null))
                if (!duplicate) haptics.warning()
            }
        }
        return true
    }

    private fun defaultRecorder(method: ScrawlCaptureMethod, hosted: Boolean): ScrawlRecorder {
        val bitRate = if (hosted) AppFrameRecorder.HOSTED_VIDEO_BIT_RATE else AppFrameRecorder.VIDEO_BIT_RATE
        val host = object : CaptureHost {
            override val lastTouchMoveNs get() = this@Scrawl.lastTouchMoveNs
            override val isInteractingForCapture get() = this@Scrawl.isInteractingForCapture
            override fun isOverlay(root: View) = root === overlay?.root
            override val keyboard get() = this@Scrawl.keyboard
            override fun focusedRoot() = this@Scrawl.focusedRoot()
            override fun hasMicrophonePermission() =
                app.checkSelfPermission(Manifest.permission.RECORD_AUDIO) == PackageManager.PERMISSION_GRANTED

            override fun requestMicrophonePermission(completion: (Boolean) -> Unit) {
                val activity = foregroundActivity ?: return completion(false)
                ScrawlRequestActivity.requestMicrophone(activity, completion)
            }
        }
        return when (method) {
            ScrawlCaptureMethod.AppFrames -> AppFrameRecorder(host, bitRate, File(app.cacheDir, "ScrawlTemp"))
            ScrawlCaptureMethod.MediaProjection -> ProjectionRecorder(app, host, { foregroundActivity ?: app }, bitRate, File(app.cacheDir, "ScrawlTemp"))
        }
    }

    companion object {
        private const val TAG = "Scrawl"
        private const val UNDO_WINDOW_MS = 5_000L
        const val LIMIT_WARNING_MS = 10_000L

        @SuppressLint("StaticFieldLeak")
        private var instance: Scrawl? = null

        /** The installed instance, if the app called [install] (no lazy creation). */
        internal val installedInstance: Scrawl? get() = instance

        /** The installed instance (after [install]). */
        @JvmStatic
        val shared: Scrawl
            get() = instance ?: error("Call Scrawl.install(application) first")

        internal val appContext: ScrawlAppContext
            get() = instance?.appContext ?: detachedContext

        /** Like iOS's singleton: screens and context set before [install] are kept, and timed once
         * the installed instance records. */
        private val detachedContext = ScrawlAppContext { instance?.elapsedSeconds() }

        /**
         * Installs ScrawlKit in this app: activity tracking, setup links, and (once configured on the
         * device) the touch observer and trigger on every app window. Unconfigured devices stay inert.
         */
        @JvmStatic
        @JvmOverloads
        fun install(application: Application, trigger: ScrawlTrigger = ScrawlTrigger.ThreeFingerLongPress, isEnabled: Boolean = true): Scrawl {
            instance?.let {
                it.trigger = trigger
                it.installed = isEnabled
                it.syncSystemIntegration()
                return it
            }
            val scrawl = Scrawl(application, resolvedConfig(application, ScrawlConfig.load(application)), sharedContext = detachedContext)
            scrawl.trigger = trigger
            scrawl.installed = isEnabled
            instance = scrawl
            application.registerActivityLifecycleCallbacks(scrawl.lifecycle)
            scrawl.notifyConfigurationChanged()
            return scrawl
        }

        val isConfigured: Boolean get() = instance?.isConfigured ?: false

        /** Handles a `<scheme>://scrawl?…` setup or reset link. */
        fun handleSetupURL(url: String): Boolean = instance?.handleSetupURL(url) ?: false

        /** Logs something the app did ("Done tapped"), placed on the recording's timeline. */
        @JvmStatic
        fun event(label: String) {
            instance?.record(label)
        }

        /** Names the screen the app is showing ("Settings › Experimental"). `null` clears it. */
        @JvmStatic
        fun screen(name: String?) = appContext.setScreen(name, ScrawlAppContext.manualToken, promote = true)

        /** Sets an app-defined value ("session" = "ses_…"). `null` clears it. */
        @JvmStatic
        fun context(key: String, value: String?) = appContext.setContext(key, value, ScrawlAppContext.manualToken, promote = true)

        /** For views/composables that manage their own token (see [ScrawlScreen]). */
        @JvmStatic
        fun setScreen(name: String?, token: UUID, promote: Boolean) = appContext.setScreen(name, token, promote)

        /** HTTPS endpoints: 3 min of app frames (~70 MB), 45 s of screen capture. */
        fun hostedRecordingLimitMs(method: ScrawlCaptureMethod): Long = when (method) {
            ScrawlCaptureMethod.AppFrames -> 180_000L
            ScrawlCaptureMethod.MediaProjection -> 45_000L
        }

        internal fun resolvedConfig(context: Context, stored: ScrawlConfig?): ScrawlConfig? {
            val (arguments, environment) = LaunchOverrides.read(context)
            return ScrawlConfig.resolved(arguments, environment, stored)
        }

        internal fun round(value: Double): Double = (value * 1000).roundToLong() / 1000.0

        private fun stampFormat() = SimpleDateFormat("yyyy-MM-dd'T'HHmmss", Locale.US).apply { timeZone = TimeZone.getTimeZone("UTC") }
        internal fun iso8601(ms: Long): String =
            SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US).apply { timeZone = TimeZone.getTimeZone("UTC") }.format(Date(ms))

        private fun deviceName(): String = listOf(Build.MANUFACTURER, Build.MODEL)
            .filter { it.isNotBlank() }
            .let { parts -> if (parts.size == 2 && parts[1].startsWith(parts[0], ignoreCase = true)) parts[1] else parts.joinToString(" ") }
            .replaceFirstChar { it.uppercase() }
    }
}

/** Launch overrides: the first activity's `scrawl-url`/`-token`/`-session` extras, and the
 * `debug.scrawl.*` system properties (`adb shell setprop debug.scrawl.url …`). */
internal object LaunchOverrides {
    var extras: Bundle? = null

    @SuppressLint("PrivateApi")
    private fun property(name: String): String? = runCatching {
        Class.forName("android.os.SystemProperties").getMethod("get", String::class.java).invoke(null, name) as String
    }.getOrNull()?.takeIf { it.isNotEmpty() }

    fun read(@Suppress("UNUSED_PARAMETER") context: Context): Pair<List<String>, Map<String, String>> {
        val arguments = mutableListOf<String>()
        extras?.let { b ->
            (b.getStringArray("scrawl-url")?.toList() ?: listOfNotNull(b.getString("scrawl-url"))).forEach { arguments += listOf("-scrawl-url", it) }
            b.getString("scrawl-token")?.let { arguments += listOf("-scrawl-token", it) }
            b.getString("scrawl-session")?.let { arguments += listOf("-scrawl-session", it) }
        }
        val environment = mutableMapOf<String, String>()
        property("debug.scrawl.url")?.let { environment["SCRAWL_URL"] = it }
        property("debug.scrawl.token")?.let { environment["SCRAWL_TOKEN"] = it }
        property("debug.scrawl.session")?.let { environment["SCRAWL_SESSION"] = it }
        return arguments to environment
    }
}

/** Pretty JSON with sorted keys, like `JSONSerialization` with `.prettyPrinted, .sortedKeys`. */
internal object Json {
    fun prettySorted(value: Any?): String = buildString { write(this, value, 0) }

    private fun write(out: StringBuilder, value: Any?, indent: Int) {
        when (value) {
            null, JSONObject.NULL -> out.append("null")
            is JSONObject -> writeMap(out, value.keys().asSequence().associateWith { value.opt(it) }, indent)
            is Map<*, *> -> writeMap(out, value.entries.associate { it.key.toString() to it.value }, indent)
            is JSONArray -> writeList(out, (0 until value.length()).map { value.opt(it) }, indent)
            is List<*> -> writeList(out, value, indent)
            is String -> out.append(JSONObject.quote(value))
            is Boolean -> out.append(value)
            is Double -> out.append(if (value == Math.floor(value) && !value.isInfinite() && kotlin.math.abs(value) < 1e15) value.toLong().toString() else value.toString())
            is Float -> write(out, value.toDouble(), indent)
            is Number -> out.append(value.toString())
            else -> out.append(JSONObject.quote(value.toString()))
        }
    }

    private fun writeMap(out: StringBuilder, map: Map<String, Any?>, indent: Int) {
        if (map.isEmpty()) {
            out.append("{}"); return
        }
        out.append("{\n")
        map.keys.sorted().forEachIndexed { i, key ->
            out.append("  ".repeat(indent + 1)).append(JSONObject.quote(key)).append(" : ")
            write(out, map[key], indent + 1)
            if (i < map.size - 1) out.append(",")
            out.append("\n")
        }
        out.append("  ".repeat(indent)).append("}")
    }

    private fun writeList(out: StringBuilder, list: List<*>, indent: Int) {
        if (list.isEmpty()) {
            out.append("[]"); return
        }
        out.append("[\n")
        list.forEachIndexed { i, item ->
            out.append("  ".repeat(indent + 1))
            write(out, item, indent + 1)
            if (i < list.size - 1) out.append(",")
            out.append("\n")
        }
        out.append("  ".repeat(indent)).append("]")
    }
}

/** Whether the network came back (iOS's `Reachability`): true when online follows offline. */
internal class Reachability {
    @Volatile private var wasSatisfied: Boolean? = null

    @Synchronized
    fun update(satisfied: Boolean): Boolean {
        val cameBack = satisfied && wasSatisfied == false
        wasSatisfied = satisfied
        return cameBack
    }
}

internal object HealthProbe {
        /**
         * Asks every address's `/health` at once, like iOS's task group: the first to answer 200 wins and
         * the rest are dropped; otherwise whether an https address said 401/403 (the link was revoked).
         */
        suspend fun probe(urls: List<String>, bearer: String): Pair<String?, Boolean> = coroutineScope {
            val results = kotlinx.coroutines.channels.Channel<Pair<String, Int?>>(urls.size)
            val connections = java.util.concurrent.ConcurrentHashMap.newKeySet<HttpURLConnection>()
            val jobs = urls.map { base ->
                launch(Dispatchers.IO) {
                    val status = runCatching {
                        val c = URL("$base/health").openConnection() as HttpURLConnection
                        connections += c
                        c.connectTimeout = 4_000
                        c.readTimeout = 4_000
                        c.setRequestProperty("Authorization", "Bearer $bearer")
                        try {
                            c.responseCode
                        } finally {
                            connections -= c
                            c.disconnect()
                        }
                    }.getOrNull()
                    results.send(base to status)
                }
            }
            var revoked = false
            var winner: String? = null
            for (i in urls.indices) {
                val (base, status) = results.receive()
                if (status == 200) {
                    winner = base
                    break
                }
                if ((status == 401 || status == 403) && base.lowercase().startsWith("https")) revoked = true
            }
            if (winner != null) {
                jobs.forEach { it.cancel() }
                connections.forEach { runCatching { it.disconnect() } }
                return@coroutineScope winner to false
            }
            null to revoked
        }
}
