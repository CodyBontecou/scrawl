    private fun share(files: List<File>, cleanup: Boolean = false) {
        val activity = foregroundActivity ?: return
        val authority = "${app.packageName}.scrawl.files"
        val uris = runCatching { files.map { FileProvider.getUriForFile(app, authority, it) } }.getOrElse {
            Log.w(TAG, "Scrawl: Share needs ScrawlKit's FileProvider: ${it.message}"); return
        }
        val intent = Intent(Intent.ACTION_SEND_MULTIPLE).apply {
            type = "*/*"
            putParcelableArrayListExtra(Intent.EXTRA_STREAM, ArrayList(uris))
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        activity.startActivity(Intent.createChooser(intent, null))
        if (cleanup) shareCleanup = files
    }

