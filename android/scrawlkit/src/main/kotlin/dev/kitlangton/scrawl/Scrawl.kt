/** How a recording starts and stops. */
enum class ScrawlTrigger {
    /** Hold three fingers on the screen for half a second to start or stop. */
    ThreeFingerLongPress,

    /** No gesture: call `Scrawl.shared.start()` and `stop()` yourself. */
    None,
}

/**
 * Records your app's screen with narration, the touches that drove it, markers, freehand red
 * strokes, and app events, all on one clock, and sends the result straight to Scrawl on your Mac
 * (falling back to Share if your Mac isn't reachable).
 *
 *     class App : Application() {
 *         override fun onCreate() { super.onCreate(); Scrawl.install(this) }
 *     }
 *     Scrawl.event("Done tapped")   // optional: what the app did, on the timeline
 *
 * Scrawl is completely inert until configured on the device via a `<scheme>://scrawl?...` setup
 * link (generated by `scrawl link --scheme <scheme>`) or debug launch overrides.
 *
 * While recording, a slim strip on the screen's edge (drag its dot to move it) toggles drawing red
 * strokes, discards (with Undo), or sends to your Mac / agent. The trigger again also sends. Every
 * touch goes on the timeline with the label of the element it hit; nothing is drawn for it on screen
 * (Scrawl on the Mac draws touches from the timeline). Holding still gives a tick.
 */
