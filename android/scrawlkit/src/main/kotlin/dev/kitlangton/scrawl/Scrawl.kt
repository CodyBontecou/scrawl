    private fun applyConfig(config: ScrawlConfig?) {
        val effective = teamEndpoint?.let { ScrawlConfig.of(listOf(it.first), it.second) } ?: config
        urlsValue = effective?.urls ?: emptyList()
        tokenValue = effective?.token
        sessionID = effective?.sessionID
