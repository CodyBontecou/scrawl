     * Cheap preparation when a configured host sees a potential trigger. No audio, capture,
     * permission request or disk work; the hidden overlay is released if the press is abandoned.
     */
    fun prepareToStart() {
        if (!isConfigured || isRecording || isStarting || overlay != null) return
