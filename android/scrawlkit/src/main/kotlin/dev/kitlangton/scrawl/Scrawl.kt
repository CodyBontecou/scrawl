    // HTTPS outbox

    private val hostedURL: String? get() = serverURLs.firstOrNull { it.lowercase().startsWith("https://") }

    private fun syncOutbox() {
        val bearer = token?.trim() ?: ""
        val target = hostedURL
        if (!isConfigured || target == null || bearer.isEmpty()) {
            tearDownOutbox(); return
        }
        val outbox = outbox ?: makeOutbox()
        outbox.setCredentials(target, bearer)
        val previous = outboxCredentials
        if (previous != null && (previous.first != target || previous.second != bearer)) {
            // A new link: what failed with the old one (revoked) gets another go.
            pairingRevoked = false
            outbox.retryFailed()
        }
        outboxCredentials = target to bearer
        OutboxWorker.schedule(app, outbox)
    }

    internal fun outboxForWorker(): Outbox? {
        syncOutbox(); return outbox
    }

    private fun makeOutbox(): Outbox {
        val outbox = Outbox(File(app.noBackupFilesDir, "ScrawlOutbox")) { event -> main.launch { handle(event) } }
        this.outbox = outbox
        // Back online: try everything waiting now rather than at its backoff time.
        val connectivity = app.getSystemService(ConnectivityManager::class.java)
        if (connectivity != null && Build.VERSION.SDK_INT >= 24) {
            val reachability = Reachability()
            val callback = object : ConnectivityManager.NetworkCallback() {
                override fun onCapabilitiesChanged(network: Network, caps: NetworkCapabilities) =
                    update(caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_VALIDATED) || caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET))

                override fun onLost(network: Network) = update(false)

                fun update(satisfied: Boolean) {
                    if (reachability.update(satisfied)) this@Scrawl.outbox?.kick(true)
                    main.launch { pathChanged(satisfied) }
                }
            }
            // NWPathMonitor's first update says "unsatisfied" when offline; Android's default-network
            // callback says nothing until a network appears. Start from what's there now, so coming
            // online after an offline launch counts as coming back.
            if (runCatching { connectivity.activeNetwork }.getOrNull() == null) {
                reachability.update(false)
                main.launch { pathChanged(false) }
            }
            runCatching { connectivity.registerDefaultNetworkCallback(callback) }
            networkCallback = callback
        }
        // Launch: whatever was waiting from earlier sessions.
        outbox.kick(true)
        return outbox
    }

    private fun tearDownOutbox() {
        val outbox = outbox ?: return
        outbox.invalidate()
        this.outbox = null
        outboxCredentials = null
        networkCallback?.let { cb -> runCatching { app.getSystemService(ConnectivityManager::class.java)?.unregisterNetworkCallback(cb) } }
        networkCallback = null
        pathSatisfied = true
        delivery = null
        stallCheck?.cancel(); stallCheck = null
        pendingSent = null
    }

    private fun handle(event: Outbox.Event) {
        if (event is Outbox.Event.Failed && event.failure == Outbox.Failure.Unauthorized) pairingRevoked = true
        val delivery = delivery
        if (delivery != null && delivery.entry == event.id) {
            delivery.apply(event, System.currentTimeMillis())
            refreshDelivery()
            return
        }
        when (event) {
            // Sent from an earlier recording or launch: say so when there's a chance.
            is Outbox.Event.Sent -> {
                pendingSent = event.reply; showPendingSent()
            }
            is Outbox.Event.Failed -> {
                if (!isIdleForStatus) return
                main.launch { presentFailure(StripFailure.of(event.failure), entry = event.id) }
            }
            else -> Unit
        }
    }

    private fun pathChanged(satisfied: Boolean) {
        if (satisfied == pathSatisfied) return
        pathSatisfied = satisfied
        delivery?.setPath(satisfied, System.currentTimeMillis())
        refreshDelivery()
    }

    private val isAppActive: Boolean get() = resumedActivities > 0

    /** Nothing is recording or on the strip, and the app is in front. */
    private val isIdleForStatus: Boolean
        get() = isAppActive && !isRecording && !isStarting && uploadStatus == UploadStatus.Idle && !isDiscardPending

    private val showsDelivery: Boolean
        get() = delivery != null && shownEntry == delivery?.entry && (uploadStatus == UploadStatus.Sending || uploadStatus == UploadStatus.Queued)

    private fun refreshDelivery() {
        stallCheck?.cancel(); stallCheck = null
        val delivery = delivery ?: return
        val now = System.currentTimeMillis()
        val showing = showsDelivery
        when (val display = delivery.display(now)) {
            is DeliveryTracker.Display.Sending, is DeliveryTracker.Display.StillSending -> {
                sendProgress = when (display) {
                    is DeliveryTracker.Display.Sending -> display.progress
                    is DeliveryTracker.Display.StillSending -> display.progress
                    else -> null
                }
                isSendStalled = display is DeliveryTracker.Display.StillSending
                if (showing && uploadStatus == UploadStatus.Queued) {
                    // A retry started on a working network: back to "Sending…".
                    statusID += 1
                    uploadStatus = UploadStatus.Sending
                }
                refreshStrip()
                delivery.nextChange(now)?.let { next ->
                    stallCheck = main.launch {
                        delay(next - now + 50)
                        refreshDelivery()
                    }
                }
            }
            DeliveryTracker.Display.Queued -> if (showing && uploadStatus == UploadStatus.Sending) presentQueued()
            is DeliveryTracker.Display.Sent -> {
                this.delivery = null
                if (showing && isAppActive) {
                    shownEntry = null
                    main.launch { presentSent(display.reply) }
                } else {
                    pendingSent = display.reply
                    showPendingSent()
                }
            }
            is DeliveryTracker.Display.Failed -> {
                this.delivery = null
                if (!showing && !isIdleForStatus) return
                shownEntry = null
                main.launch { presentFailure(StripFailure.of(display.failure), entry = delivery.entry) }
            }
        }
    }

    /** Shows a "Sent to …" that couldn't be shown when the upload landed. */
    private fun showPendingSent() {
        val reply = pendingSent ?: return
        if (!isAppActive || isRecording || isStarting || isDiscardPending) return
        val staleStatus = delivery == null && shownEntry != null && (uploadStatus == UploadStatus.Sending || uploadStatus == UploadStatus.Queued)
        if (uploadStatus != UploadStatus.Idle && !staleStatus) return
        shownEntry = null
        showOverlay()
        main.launch { presentSent(reply) }
    }

    // Public controls

    /** Starts recording, or sends the current recording. */
    fun toggle() {
        if (!isConfigured) return
        if (isRecording || isStarting) stop() else start()
    }

    fun toggleDrawing() {
        if (!isRecording && !isStarting) return
        isDrawing = !isDrawing
        haptics.light()
        refreshStrip()
    }

    fun start() {
        if (!isConfigured || isRecording || isStarting) return
        start(startupObserver?.let { StartupTrace(it) })
    }

    /** Starts the measurement at recognition, before the trigger's feedback work. */
    internal fun triggerRecognized() {
        if (!isConfigured) return
        val trace = if (!isRecording && !isStarting) startupObserver?.let { StartupTrace(it) } else null
        haptics.success()
        if (isRecording || isStarting) stop() else start(trace)
    }

    private fun start(trace: StartupTrace?) {
        if (!isConfigured || isRecording || isStarting) return
        prewarmExpiry?.cancel(); prewarmExpiry = null
        startupTrace = trace
        val hosted = hostedURL != null
        if (isDiscardPending) finalizeDiscard()
        markers = emptyList()
        events = mutableListOf()
        touchLog = mutableListOf()
        strokeLog = mutableListOf()
        completedStrokes = emptyList()
        overlay?.clearInk(animated = false)
        lastTouchLog.clear()
        touchLabels.clear()
        // Fingers already down (the three-finger trigger) are never logged.
        touchIDs.clear()
        nextTouchID = 1
        holdStarts.clear()
        draggingTouchIDs.clear()
        lastTouchMoveNs = null
        isDrawing = false
        failedRecording = null
        failedEntry = null
        shownEntry = null
        delivery = null
        stallCheck?.cancel(); stallCheck = null
        statusID += 1
        isStarting = true
        pendingFinish = null
        startedAt = RecordingStart.now()
        uploadStatus = UploadStatus.Idle
        showOverlay()
        preparedAt = null
        refreshStrip()
        val recorder = makeRecorder?.invoke(captureMethod, hosted) ?: defaultRecorder(captureMethod, hosted)
        recorder.startupTrace = startupTrace
        startupTrace?.mark("recorderCreated")
        if (!recorder.isAvailable) {
            isStarting = false
            startedAt = null
            hideOverlay()
            return
        }
        this.recorder = recorder
        recorder.onInterruption = { stop() }
        val begin: () -> Unit = begin@{
            if (this.recorder !== recorder || !isStarting) return@begin
            if (hosted) main.launch {
                trace?.mark("outboxBegin")
                syncOutbox()
                trace?.mark("outboxEnd")
                if (pairingRevoked) showNotice(StripNotice.linkExpired, 5_000)
            }
            main.launch { findMac() }
            recorder.start(narration) { result ->
                if (this.recorder !== recorder || !isStarting) return@start
                isStarting = false
                result.onSuccess { started ->
                    startupTrace?.mark("ready")
                    // Touches and drawing are accepted while the hardware starts: keep their times on
                    // the movie's clock.
                    val shift = (startedAt?.monoNs?.let { (it - started.monoNs) / 1e9 }) ?: 0.0
                    rebaseEarlyInput(shift)
                    startedAt = started
                    keyboard.recordingWillBegin()
                    appContext.begin()
                    isRecording = true
                    refreshStrip()
                    if (hosted) startLimit(recorder.method, started)
                    pendingFinish?.let { discarding ->
                        pendingFinish = null
                        finish(discarding)
                    }
                }.onFailure { error ->
                    Log.w(TAG, "Scrawl: could not start recording: ${error.message}")
                    this.recorder = null
                    startedAt = null
                    pendingFinish = null
                    isDrawing = false
                    hideOverlay()
                }
            }
        }
        val overlay = overlay
        if (overlay != null) overlay.afterFirstPresentation(begin) else begin()
    }

    /** Stops recording and sends it to your Mac (the strip's Send). */
    fun stop() = finish(discarding = false)

    /** Stops recording without sending it. Undo (which sends it) is offered for a few seconds. */
    fun discard() {
        if (!isRecording && !isStarting) return
        haptics.light()
        finish(discarding = true)
    }

    /** The discarded toast's Undo: sends the recording after all. */
    internal fun undoDiscard() {
        if (!isDiscardPending) return
        isDiscardPending = false
        uploadStatus = UploadStatus.Sending
        haptics.light()
        val finished = discarded
        if (finished != null) {
            discarded = null
            main.launch { deliver(finished) }
        } else {
            undoneDiscardID = discardID
        }
    }

    private fun finish(discarding: Boolean) {
        if (isStarting) {
            pendingFinish = discarding; return
        }
        val startedAt = startedAt
        val recorder = recorder
        if (!isRecording || startedAt == null || recorder == null) return
        this.recorder = null
        isRecording = false
        isDrawing = false
        limitTask?.cancel(); limitTask = null
        notice = null
        val discardToken = if (discarding) beginUndoWindow() else null
        if (discardToken == null) uploadStatus = UploadStatus.Sending
        // Recordings for an HTTPS endpoint stay out of shared storage: they're staged in the cache
        // and live on only inside the outbox.
        val directory = if (hostedURL != null) stagingDirectory else recordingsDirectory
        directory.mkdirs()
        val stamp = stampFormat().format(Date(startedAt.wallMs))
        val movie = File(directory, "$stamp.mp4")
        val timeline = File(directory, "$stamp.json")
        val readyMarker = File(directory, "$stamp.ready")
        val sentMarker = File(directory, "$stamp.sent")
        val pm = app.packageManager
        val appName = app.applicationInfo.loadLabel(pm).toString().ifEmpty { app.packageName }
        val packageInfo = runCatching { pm.getPackageInfo(app.packageName, 0) }.getOrNull()
        val density = touchWindow?.resources?.displayMetrics?.density ?: 0f
        val info = linkedMapOf<String, Any?>(
            "app" to appName,
            "bundleId" to app.packageName,
            "version" to (packageInfo?.let { if (Build.VERSION.SDK_INT >= 28) it.longVersionCode else @Suppress("DEPRECATION") it.versionCode.toLong() }?.toString() ?: ""),
            "shortVersion" to (packageInfo?.versionName ?: ""),
            "device" to deviceName(),
            "system" to "Android ${Build.VERSION.RELEASE}",
            // Touches are in this window's dp (portrait or landscape as it was recorded).
            "screen" to JSONObject().apply {
                // No touches: zeros, as iOS writes for a nil touch window.
                put("width", if (density > 0) (touchWindow?.width ?: 0) / density.toDouble() else 0.0)
                put("height", if (density > 0) (touchWindow?.height ?: 0) / density.toDouble() else 0.0)
                put("scale", density.toDouble())
            },
            "recordedAt" to iso8601(startedAt.wallMs),
            "duration" to round((System.currentTimeMillis() - startedAt.wallMs) / 1000.0),
            "markers" to JSONArray(markers),
            "events" to JSONArray(events),
            "touches" to JSONArray(touchLog),
            "strokes" to JSONArray(strokeLog),
            "capture" to recorder.method.raw,
        )
        sessionID?.takeIf { it.isNotEmpty() }?.let { info["session"] = it }
        for ((key, value) in appContext.end()) if (key !in info) info[key] = value
        this.startedAt = null
        completedStrokes = emptyList()
        overlay?.clearInk(animated = true)
        refreshStrip()
        recorder.stop(movie) { error ->
            main.launch {
                if (error != null) {
                    Log.w(TAG, "Scrawl: recording failed: ${error.message}")
                    uploadStatus = UploadStatus.Idle
                    if (discardToken == discardID) isDiscardPending = false
                    refreshStrip()
                    hideOverlayAfterExit()
                    return@launch
                }
                info["audio"] = recorder.recordsAudio
                timelineSupplement?.let { supplement ->
                    for ((key, value) in supplement(JSONObject(info as Map<*, *>))) info[key] = value
                }
                val timelineData = Json.prettySorted(info).toByteArray()
                runCatching { timeline.writeBytes(timelineData) }
                val finished = FinishedRecording(Recording(movie, timeline), timelineData, readyMarker, sentMarker, iso8601(startedAt.wallMs))
                if (discardToken == null) {
                    deliver(finished); return@launch
                }
                when {
                    undoneDiscardID == discardToken -> {
                        undoneDiscardID = null
                        deliver(finished)
                    }
                    isDiscardPending && discardID == discardToken -> discarded = finished
                    else -> delete(finished)
                }
            }
        }
    }

    /** Shows the discarded toast and deletes the recording when its Undo window runs out. */
    private fun beginUndoWindow(): Int {
        discardID += 1
        val id = discardID
        discarded = null
        undoneDiscardID = null
        isDiscardPending = true
        refreshStrip()
        main.launch {
            delay(UNDO_WINDOW_MS)
            if (!isDiscardPending || discardID != id) return@launch
            finalizeDiscard()
            hideOverlayAfterExit()
        }
        return id
    }

    /** Ends the Undo window now. A recording still being written is deleted when it lands. */
    private fun finalizeDiscard() {
        isDiscardPending = false
        discarded?.let { delete(it) }
        discarded = null
        refreshStrip()
    }

    private fun delete(finished: FinishedRecording) {
        listOf(finished.recording.movie, finished.recording.timeline, finished.readyMarker, finished.sentMarker, deliveryMarker(finished.sentMarker))
            .forEach { it.delete() }
    }

    private suspend fun deliver(finished: FinishedRecording) {
        val submitted = onRecordingSubmitted
        if (submitted != null && submitted(finished.recording.timeline, finished.recording.movie)) {
            uploadStatus = UploadStatus.Idle
            delete(finished)
            hideOverlayAfterExit()
            return
        }
        if (hostedURL != null) {
            deliverHosted(finished); return
        }
        // `.ready` lets the Mac pick the recording up over USB (adb) if the network fails.
        runCatching { finished.readyMarker.writeText("ready") }
        recordings += finished.recording
        deliverToMacOrShare(finished)
    }

