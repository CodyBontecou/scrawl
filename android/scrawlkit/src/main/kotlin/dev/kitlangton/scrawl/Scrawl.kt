    /** Hides the overlay once the strip has animated away, unless something new took over. */
    private suspend fun hideOverlayAfterExit() {
        delay(StripMotion.overlayLingerMs)
        if (isRecording || isStarting || uploadStatus != UploadStatus.Idle || isDiscardPending) return
        if (pendingSent != null && isAppActive) {
            showPendingSent(); return
        }
        hideOverlay()
    }

    /** The strip's mode, by precedence: recording, prepared, discarded, upload status. */
    private val stripMode: StripMode?
        get() {
            val started = startedAt
            if ((isRecording || isStarting) && started != null) return StripMode.Recording(started.wallMs, isDrawing)
            preparedAt?.let { return StripMode.Recording(it, false) }
            if (isDiscardPending) return StripMode.Discarded
            return when (val status = uploadStatus) {
                UploadStatus.Idle -> null
                UploadStatus.Sending -> StripMode.Sending(sendProgress, isSendStalled)
                is UploadStatus.Sent -> StripMode.Sent(status.reply)
                UploadStatus.Queued -> StripMode.Queued
                UploadStatus.Failed -> StripMode.Failed(deliveryFailure)
            }
        }

    private fun refreshStrip() {
        overlay?.update(stripMode, if (isRecording) notice else null)
    }

